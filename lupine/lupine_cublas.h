  uint8_t alpha_data[16] = {};
  uint8_t beta_data[16] = {};
  uint64_t descriptor = 0;
  uint64_t a_descriptor = 0;
  uint64_t b_descriptor = 0;
  uint64_t c_descriptor = 0;
  uint64_t d_descriptor = 0;
  uint64_t preference = 0;
