  int32_t k = 0;
  int32_t lda = 0;
  int32_t ldb = 0;
  int32_t ldc = 0;
  int32_t value = 0;
  float alpha = 0.0f;
  float beta = 0.0f;
  int32_t a_type = 0;
  int32_t b_type = 0;
  int32_t c_type = 0;
